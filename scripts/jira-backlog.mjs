/** CSV s úvodzovkami podľa RFC 4180 — opis obsahuje čiarky aj zalomenia. */
function pole(t) {
  const s = String(t ?? "");
  return /[",\n]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s;
}

const riadky = [];
riadky.push(
  [
    "Issue Type",
    "Summary",
    "Description",
    "Status",
    "Priority",
    "Labels",
    "Epic Name",
    "Epic Link",
    "Created",
    "Resolved",
  ].join(","),
);

// Epiky ako prvé — Jira ich musí poznať skôr, než na ne úlohy odkážu.
for (const [nazov, popis] of EPIKY) {
  riadky.push(
    [
      pole("Epic"),
      pole(nazov),
      pole(popis),
      pole("To Do"),
      pole("Medium"),
      pole("eticketo"),
      pole(nazov),
      pole(""),
      pole("2026-05-29 12:00"),
      pole(""),
    ].join(","),
  );
}

for (const [epika, typ, nazov, opis, stav, priorita, datum, stitok] of U) {
  if (!EPIKY.some(([e]) => e === epika)) throw new Error(`Neznáma epika: ${epika}`);
  riadky.push(
    [
      pole(typ),
      pole(nazov),
      pole(opis),
      pole(stav),
      pole(priorita),
      pole(stitok),
      pole(""),
      pole(epika),
      pole(datum),
      pole(stav === "Done" ? datum : ""),
    ].join(","),
  );
}

const csv = riadky.join("\n") + "\n";
if (process.argv[2]) {
  fs.writeFileSync(process.argv[2], csv, "utf8");
  const done = U.filter((u) => u[4] === "Done").length;
  const vProcese = U.filter((u) => u[4] === "In Progress").length;
  const todo = U.filter((u) => u[4] === "To Do").length;
  console.log(`Zapísané do ${process.argv[2]}`);
  console.log(
    `Epík: ${EPIKY.length}, úloh: ${U.length} (hotové ${done}, rozrobené ${vProcese}, čaká ${todo})`,
  );
} else {
  process.stdout.write(csv);
}
